#!/usr/bin/env python3
"""Parse room_temp_log.txt into a CSV and a descriptive summary.

Uses only the Python standard library. Does not diagnose causes or infer causation.
"""
from __future__ import annotations

import argparse
import csv
import re
from datetime import datetime
from pathlib import Path
from statistics import mean, median

LINE_RE = re.compile(
    r"^(?P<timestamp>\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\s*->\s*"
    r"(?P<temperature>-?\d+(?:\.\d+)?)\s*°?\s*F\s*$",
    re.IGNORECASE,
)


def parse_log(path: Path):
    readings = []
    invalid_lines = []
    for line_number, raw_line in enumerate(
        path.read_text(encoding="utf-8-sig", errors="replace").splitlines(), start=1
    ):
        line = raw_line.strip()
        if not line or line.startswith("--- Log Started:"):
            continue
        match = LINE_RE.match(line)
        if not match:
            invalid_lines.append((line_number, line))
            continue
        try:
            timestamp = datetime.strptime(match.group("timestamp"), "%Y-%m-%d %H:%M:%S")
            temperature_f = float(match.group("temperature"))
        except ValueError:
            invalid_lines.append((line_number, line))
            continue
        readings.append((timestamp, temperature_f, line_number))
    readings.sort(key=lambda item: item[0])
    return readings, invalid_lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="Path to room_temp_log.txt")
    parser.add_argument("--csv", type=Path, default=Path("temperature_readings.csv"))
    parser.add_argument("--report", type=Path, default=Path("temperature_summary.txt"))
    args = parser.parse_args()

    if not args.input.is_file():
        parser.error(f"input file does not exist: {args.input}")

    readings, invalid_lines = parse_log(args.input)
    if not readings:
        print("No valid temperature readings were found. Check the input format.")
        if invalid_lines:
            print(f"Unparsed non-header lines: {len(invalid_lines)}")
        return 1

    args.csv.parent.mkdir(parents=True, exist_ok=True)
    with args.csv.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["timestamp", "temperature_f"])
        for timestamp, temperature_f, _ in readings:
            writer.writerow([timestamp.isoformat(sep=" "), f"{temperature_f:.2f}"])

    temperatures = [item[1] for item in readings]
    intervals = [
        (readings[i][0] - readings[i - 1][0]).total_seconds()
        for i in range(1, len(readings))
    ]
    report_lines = [
        "Room Temperature Logger — Descriptive Summary",
        "==============================================",
        f"Input file: {args.input}",
        f"Valid readings: {len(readings)}",
        f"Unparsed non-header lines: {len(invalid_lines)}",
        f"First timestamp: {readings[0][0]}",
        f"Last timestamp: {readings[-1][0]}",
        f"Elapsed span (hours): {(readings[-1][0] - readings[0][0]).total_seconds() / 3600:.2f}",
        f"Minimum (°F): {min(temperatures):.2f}",
        f"Maximum (°F): {max(temperatures):.2f}",
        f"Mean (°F): {mean(temperatures):.2f}",
        f"Median (°F): {median(temperatures):.2f}",
    ]
    if intervals:
        report_lines.extend([
            f"Median interval between readings (seconds): {median(intervals):.1f}",
            f"Intervals greater than 10 seconds: {sum(seconds > 10 for seconds in intervals)}",
        ])
    report_lines.extend([
        "",
        "Interpretation cautions:",
        "- These are descriptive statistics from the provided sensor log, not calibrated measurements.",
        "- Timestamps are generated by PowerShell when serial lines are received.",
        "- Large gaps may indicate logging interruptions or missing sensor readings.",
        "- This report cannot establish the cause of any health symptom.",
    ])
    if invalid_lines:
        report_lines.extend(["", "Unparsed lines (line number: content):"])
        report_lines.extend(f"{number}: {line}" for number, line in invalid_lines[:50])
        if len(invalid_lines) > 50:
            report_lines.append(f"... {len(invalid_lines) - 50} additional lines omitted")

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(report_lines) + "\n", encoding="utf-8")
    print(f"Parsed {len(readings)} readings.")
    print(f"CSV written to: {args.csv}")
    print(f"Summary written to: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
